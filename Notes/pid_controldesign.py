import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
import control as ctrl

# Plant
num = [165702.47]
den = [1.0, 390.2, 15701.0]
G = ctrl.TransferFunction(num, den)

# transfer function
print(G)
t = np.linspace(0, 0.2, 20001)
t, y = ctrl.step_response(G, T=t)

plt.plot(t, y)
plt.show()
# Find parameters for Cohen-Coon method
# Steady-state value
K = y[-1]

# Find time when response reaches 28.3% and 63.2% of final value
y_283 = 0.283 * K
y_632 = 0.632 * K

# Find corresponding times
idx_283 = np.argmax(y >= y_283)
idx_632 = np.argmax(y >= y_632)

tau = t[idx_632] - t[idx_283]
theta = t[idx_283]

print(f"System parameters:")
print(f"K = {K:.4f}")
print(f"τ = {tau:.4f}")
print(f"θ = {theta:.4f}")
print(f"θ/τ = {theta/tau:.4f}")

# Cohen-Coon tuning calculations
K_process = K
tau_process = tau
theta_process = theta
ratio = theta_process / tau_process

# P Controller
Kc_P = 20*(1/K_process) * (tau_process/theta_process) * (1 + theta_process/(3*tau_process))

# PI Controller
Kc_PI = (1/K_process) * (0.9*tau_process/theta_process) * (1 + theta_process/(12*tau_process))
tau_I = theta_process * (30 + 3*ratio) / (9 + 20*ratio)

# PID Controller
Kc_PID = (1/K_process) * (4*tau_process/(3*theta_process)) * (1 + theta_process/(4*tau_process))
tau_I_PID = theta_process * (32 + 6*ratio) / (13 + 8*ratio)
tau_D = theta_process * 4 / (11 + 2*ratio)

print(f"\nCohen-Coon Tuning Parameters:")
print(f"P Controller: Kc = {Kc_P:.4f}")
print(f"PI Controller: Kc = {Kc_PI:.4f}, τI = {tau_I:.4f}")
print(f"PID Controller: Kc = {Kc_PID:.4f}, τI = {tau_I_PID:.4f}, τD = {tau_D:.4f}")

# Create controllers
# P Controller
s = ctrl.TransferFunction([1,0],[1])
C_P = ctrl.TransferFunction([Kc_P], [1])

# PI Controller
C_PI_num = [Kc_PI * tau_I, Kc_PI]
C_PI_den = [tau_I, 0]
C_PI = ctrl.TransferFunction(C_PI_num, C_PI_den)

# PID Controller
C_PID_num = [Kc_PID * tau_D * tau_I_PID, Kc_PID * tau_I_PID, Kc_PID]
C_PID_den = [tau_I_PID, 0]
C_PID = ctrl.TransferFunction(C_PID_num, C_PID_den)

# close loop Equation
G_cl_P = ctrl.feedback(C_P*G, 1)
G_cl_PI = ctrl.feedback(C_PI*G, 1)
G_cl_PID = ctrl.feedback(C_PID*G, 1)

# print of close
print(f"P Controller: {G_cl_P}")
print(f"PI Controller: {G_cl_PI}")
print(f"PID Controller: {G_cl_PID}")


