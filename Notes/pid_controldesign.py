def analyze_step_response(t, y, system_name):
    """Analyze step response and return performance metrics"""
    # Steady-state value
    y_ss = y[-1]

    # Rise time (10% to 90%)
    idx_10 = np.argmax(y >= 0.1 * y_ss)
    idx_90 = np.argmax(y >= 0.9 * y_ss)
    t_rise = t[idx_90] - t[idx_10]

    # Settling time (2% criterion)
    idx_settle = np.argmax(np.abs(y - y_ss) <= 0.02 * y_ss)
    t_settle = t[idx_settle]

    # Overshoot
    y_max = np.max(y)
    overshoot = ((y_max - y_ss) / y_ss) * 100 if y_max > y_ss else 0

    # Steady-state error
    ess = 1 - y_ss

    print(f"\n{system_name} Performance:")
    print(f"Rise Time: {t_rise*1000:.2f} ms")
    print(f"Settling Time: {t_settle*1000:.2f} ms")
    print(f"Overshoot: {overshoot:.2f}%")
    print(f"Steady-state Error: {ess:.4f}")

    return t_rise, t_settle, overshoot, ess

